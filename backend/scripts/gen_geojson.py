"""Generate approximate territory GeoJSON polygons for Five Dynasties polities.

These are simplified boundary envelopes based on modern province outlines.
For research precision, we recommend replacing with CHGIS (Chinese Historical GIS)
 polygons in the future — these polygons are good enough for the demo's dynamic
 map visualization.

Each territory is represented as a single Polygon (or MultiPolygon for fragmented holdings).
Coordinates: [longitude, latitude] in WGS84.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
GEO_DIR = ROOT / "data" / "geo"
GEO_DIR.mkdir(parents=True, exist_ok=True)


def feature(name, coords):
    """coords: list of [lng, lat] points (polygon ring)."""
    return {
        "type": "FeatureCollection",
        "features": [
            {
                "type": "Feature",
                "properties": {"name": name},
                "geometry": {
                    "type": "Polygon",
                    "coordinates": [coords],
                },
            }
        ],
    }


def multi_feature(name, polygons):
    """polygons: list of point-lists."""
    return {
        "type": "FeatureCollection",
        "features": [
            {
                "type": "Feature",
                "properties": {"name": name},
                "geometry": {
                    "type": "MultiPolygon",
                    "coordinates": [[ring] for ring in polygons],
                },
            }
        ],
    }


