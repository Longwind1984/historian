#!/usr/bin/env python3
"""Schema registry: scans schema/*.yaml and generates downstream artifacts.

Generates:
- docs/data-dictionary.md     (human-readable data dictionary)
- frontend/src/types/schema.ts (TypeScript stubs)

Usage:
    python scripts/registry.py
"""
import sys
from pathlib import Path
import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SCHEMA_DIR = ROOT / "schema"
DOCS_DIR = ROOT / "docs"
FRONTEND_TYPES = ROOT / "frontend" / "src" / "types"


def load_schemas():
    schemas = {}
    for path in sorted(SCHEMA_DIR.glob("*.yaml")):
        if path.name.startswith("_") or path.name == "relations.yaml":
            continue
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
        if data and "type" in data:
            schemas[data["type"]] = data
    return schemas


def gen_data_dictionary(schemas, rel_schema_path):
    rel_schema = yaml.safe_load(rel_schema_path.read_text())["relations"]
    lines = ["# 数据字典 · Data Dictionary\n"]
    lines.append("> Auto-generated by `scripts/registry.py`. Do not edit.\n")
    lines.append("\n## 节点类型\n")
    for t, s in schemas.items():
        lines.append(f"### {s.get('icon','')} `{t}` · {s.get('label','')}\n")
        if s.get("description"):
            lines.append(f"{s['description']}\n")
        lines.append("\n**字段：**\n")
        lines.append("| 字段 | 类型 | 必填 | 标签 | 说明 |")
        lines.append("|------|------|------|------|------|")
        for fname, fdef in (s.get("fields") or {}).items():
            req = "✓" if fdef.get("required") else ""
            ftype = fdef.get("type", "")
            label = fdef.get("label", "")
            desc = fdef.get("description", "")
            lines.append(f"| `{fname}` | {ftype} | {req} | {label} | {desc} |")
        if s.get("ext") == "allow":
            lines.append("\n*允许 `ext` 自由扩展字段。*\n")

    lines.append("\n## 关系类型\n")
    lines.append("| type | 标签 | 方向 | 颜色 |")
    lines.append("|------|------|------|------|")
    for r in rel_schema:
        direction = "→" if r.get("directional") else "↔"
        lines.append(f"| `{r['type']}` | {r.get('label','')} | {direction} | {r.get('color','')} |")

    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    out = DOCS_DIR / "data-dictionary.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"  → {out.relative_to(ROOT)}")


def gen_ts(schemas):
    FRONTEND_TYPES.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Auto-generated by scripts/registry.py. Do not edit.",
        "export type EntityType = " + " | ".join(f'"{t}"' for t in schemas.keys()) + ";",
        "",
    ]
    for t, s in schemas.items():
        lines.append(f"export interface {t} {{")
        lines.append(f"  id: string;")
        lines.append(f"  type: '{t}';")
        for fname, fdef in (s.get("fields") or {}).items():
            ts_type = _ts_type(fdef)
            opt = "" if fdef.get("required") else "?"
            lines.append(f"  {fname}{opt}: {ts_type};")
        lines.append(f"  ext?: Record<string, any>;")
        lines.append("}")
        lines.append("")
    out = FRONTEND_TYPES / "schema.ts"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"  → {out.relative_to(ROOT)}")


def _ts_type(fdef):
    t = fdef.get("type", "string")
    if t in ("string", "url"):
        return "string"
    if t in ("int", "year"):
        return "number"
    if t == "year_month":
        return "{ year: number; month?: number } | null"
    if t == "text":
        return "string"
    if t == "number":
        return "number"
    if t == "array":
        items = fdef.get("items", {})
        if isinstance(items, dict):
            itype = items.get("type", "string")
            if itype == "ref":
                return f"Array<{items.get('to','any')}>"
            return f"Array<{_ts_type(items)}>"
        return "any[]"
    if t == "enum":
        opts = fdef.get("options", [])
        return " | ".join(f'"{o}"' for o in opts) if opts else "string"
    if t == "ref":
        return f"{fdef.get('to','any')} | string"
    return "any"


def main():
    print("→ Generating artifacts from schema…")
    schemas = load_schemas()
    gen_data_dictionary(schemas, SCHEMA_DIR / "relations.yaml")
    gen_ts(schemas)
    print("✓ Done")


if __name__ == "__main__":
    main()
