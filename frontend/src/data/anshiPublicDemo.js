const ARGUMENT_NODE_LAYERS = Object.freeze({
  question: 'platform_inference',
  material_observation: 'author_judgment',
  reasoning_mechanism: 'platform_inference',
  action_or_turn: 'historical_fact',
  consequence: 'author_judgment',
  limitation: 'uncertainty',
})

const publicArgumentGraph = (slug, anchorId, locatorLabel, content) => {
  const node = (type, value) => Object.freeze({
    id: `${slug}-${type}`,
    type,
    title: value.title,
    summary: value.summary,
    detail: value.detail,
    epistemicLayer: value.epistemicLayer || ARGUMENT_NODE_LAYERS[type],
    anchorId,
    locatorLabel,
    accessState: 'restricted',
  })
  const nodes = Object.freeze([
    node('question', content.question),
    node('material_observation', content.materialObservation),
    node('reasoning_mechanism', content.reasoningMechanism),
    node('action_or_turn', content.actionOrTurn),
    node('consequence', content.consequence),
    node('limitation', content.limitation),
  ])
  const edge = (from, to, relation, label) => Object.freeze({
    id: `${slug}-${from}-${to}`,
    from: `${slug}-${from}`,
    to: `${slug}-${to}`,
    relation,
    label,
  })
  return Object.freeze({
    id: `${slug}-argument-graph`,
    anchorId,
    locatorLabel,
    accessState: 'restricted',
    nodes,
    edges: Object.freeze([
      edge('question', 'material_observation', 'frames', '以材料观察回应'),
      edge('material_observation', 'reasoning_mechanism', 'grounds', '支撑机制判断'),
      edge('reasoning_mechanism', 'action_or_turn', 'explains', '解释行动转折'),
      edge('action_or_turn', 'consequence', 'leads_to', '导向后果'),
      edge('question', 'limitation', 'frames', '同步声明未知'),
      edge('limitation', 'reasoning_mechanism', 'qualifies', '限制解释强度'),
      edge('limitation', 'consequence', 'qualifies', '限制后果外推'),
    ]),
  })
}

