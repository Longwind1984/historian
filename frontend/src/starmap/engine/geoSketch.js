/**
 * Catmull-Rom 平滑插值（开放折线,端点重复,过所有锚点）。
 * @param {number[][]} anchors [[lng,lat],...]
 * @param {number} perSeg 每段插入点数(任务书:2-3 即可)
 * @returns {number[][]} 平滑后折线 [[lng,lat],...]
 */
export function smooth(anchors, perSeg = 3) {
  const n = anchors.length;
  if (n < 2) return anchors.slice();
  const out = [];
  for (let i = 0; i < n - 1; i++) {
    const p0 = anchors[i - 1] || anchors[i];
    const p1 = anchors[i];
    const p2 = anchors[i + 1];
    const p3 = anchors[i + 2] || anchors[i + 1];
    out.push(p1);
    for (let j = 1; j <= perSeg; j++) {
      const t = j / (perSeg + 1);
      const t2 = t * t, t3 = t2 * t;
      out.push([
        0.5 * ((2 * p1[0]) + (-p0[0] + p2[0]) * t + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2 + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3),
        0.5 * ((2 * p1[1]) + (-p0[1] + p2[1]) * t + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2 + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3),
      ]);
    }
  }
  out.push(anchors[n - 1]);
  return out;
}
