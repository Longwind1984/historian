    segs.sort()
    issues=[]
    if segs and segs[0][0]!=lo: issues.append(f"起点 {segs[0][0]} != 朝代起 {lo}")
    if segs and segs[-1][1]!=hi: issues.append(f"讫点 {segs[-1][1]} != 朝代讫 {hi}")
    for (a1,b1,i1),(a2,b2,i2) in zip(segs, segs[1:]):
        if b1 < a2: issues.append(f"缺口 {b1}~{a2} ({i1}→{i2})")
        elif b1 > a2: issues.append(f"重叠 {a2}~{b1} ({i1}×{i2})")
    print(f"  {label}: {len(segs)} 帝 " + ("✓ 链完整" if not issues else "⚠ " + "; ".join(issues)))
